describe("CombatQueue", function()
	local ns

	before_each(function()
		ns = {}
		assert(loadfile("MerrinxUI/Util/CombatQueue.lua"))("MerrinxUI", ns)
	end)

	it("drains in first-push order", function()
		local q = ns.CombatQueue.New()
		local order = {}
		q:Push("a", function()
			table.insert(order, "a")
		end)
		q:Push("b", function()
			table.insert(order, "b")
		end)
		q:Push("c", function()
			table.insert(order, "c")
		end)
		q:Drain()
		assert.are.same({ "a", "b", "c" }, order)
	end)

	it("keeps the first position when the last fn pushed per key wins", function()
		local q = ns.CombatQueue.New()
		local order = {}
		q:Push("a", function()
			table.insert(order, "a1")
		end)
		q:Push("b", function()
			table.insert(order, "b")
		end)
		q:Push("a", function()
			table.insert(order, "a2")
		end)
		q:Drain()
		assert.are.same({ "a2", "b" }, order)
	end)

	it("snapshots the drain: a push inside a drained fn runs on the next Drain", function()
		local q = ns.CombatQueue.New()
		local order = {}
		q:Push("a", function()
			table.insert(order, "a")
			q:Push("b", function()
				table.insert(order, "b")
			end)
		end)
		q:Drain()
		assert.are.same({ "a" }, order)
		q:Drain()
		assert.are.same({ "a", "b" }, order)
	end)

	it("is a no-op on an empty queue", function()
		local q = ns.CombatQueue.New()
		assert.has_no.errors(function()
			q:Drain()
		end)
	end)
end)
